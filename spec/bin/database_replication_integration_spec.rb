# frozen_string_literal: true

require 'open3'
require 'securerandom'
require 'tmpdir'
require 'zlib'

RSpec.describe 'database replication with PostgreSQL' do
  attr_reader :backup_script,
              :command_log,
              :database_user,
              :dump_file,
              :full_dump_file,
              :pg_dump_container,
              :real_pg_dump,
              :real_pg_restore,
              :real_psql,
              :replicate_script,
              :target_database,
              :tempdir

  def run_command(*command, stdin_data: '')
    stdout, stderr, status = Open3.capture3(*command, stdin_data:)
    raise "#{command.join(' ')} failed:\n#{stdout}\n#{stderr}" unless status.success?

    stdout
  end

  def psql(database, sql)
    run_command('psql', '-X', '--username', database_user, '-v', 'ON_ERROR_STOP=1', '-q', database, '-c', sql)
  end

  def query(database, sql)
    run_command('psql', '-X', '--username', database_user, '-Atq', database, '-c', sql).strip
  end

  def write_executable(name, contents)
    path = File.join(tempdir, 'bin', name)
    File.write(path, contents)
    File.chmod(0o755, path)
  end

  def create_target_database
    run_command('createdb', '--username', database_user, target_database)

    psql(target_database, <<~SQL)
      CREATE TABLE restore_probe(value text);
      INSERT INTO restore_probe VALUES ('old');
      CREATE MATERIALIZED VIEW restore_probe_view AS
        SELECT value FROM restore_probe;
      CREATE FUNCTION noop_event_trigger() RETURNS event_trigger
        LANGUAGE plpgsql AS $$ BEGIN END; $$;
      CREATE EVENT TRIGGER reassign_owned
        ON ddl_command_end EXECUTE FUNCTION noop_event_trigger();
    SQL
  end

  def build_dump(include_materialized_view: true)
    source_database = "replication_source_#{SecureRandom.hex(6)}"
    run_command('createdb', '--username', database_user, source_database)

    begin
      psql(source_database, <<~SQL)
        CREATE TABLE restore_probe(value text);
        INSERT INTO restore_probe VALUES ('new');
        CREATE FUNCTION noop_event_trigger() RETURNS event_trigger
          LANGUAGE plpgsql AS $$ BEGIN END; $$;
        CREATE EVENT TRIGGER reassign_owned
          ON ddl_command_end EXECUTE FUNCTION noop_event_trigger();
      SQL
      if include_materialized_view
        psql(source_database, <<~SQL)
          CREATE MATERIALIZED VIEW restore_probe_view AS
            SELECT value FROM restore_probe WITH NO DATA;
        SQL
      end

      _stdout, stderr, status = run_backup(source_database)
      raise stderr unless status.success?
    ensure
      run_command('dropdb', '--username', database_user, '--if-exists', '--force', source_database)
    end
  end

  def install_replication_boundary_stubs
    FileUtils.mkdir_p(File.join(tempdir, 'bin'))
    FileUtils.touch(command_log)

    write_executable('aws', <<~'BASH')
      #!/usr/bin/env bash
      set -euo pipefail
      echo "aws $*" >> "$TMPDIR/commands.log"

      if [[ "$1 $2" == "ecs describe-services" ]]; then
        echo 1
      fi
    BASH

    write_executable('curl', <<~'BASH')
      #!/usr/bin/env bash
      set -euo pipefail
      echo "curl $*" >> "$TMPDIR/commands.log"

      while [[ $# -gt 0 ]]; do
        if [[ "$1" == "--output" ]]; then
          cp "$DUMP_FIXTURE" "$2"
          exit 0
        fi
        shift
      done

      exit 1
    BASH

    write_executable('psql', <<~'BASH')
      #!/usr/bin/env bash
      set -euo pipefail
      echo "psql $*" >> "$TMPDIR/commands.log"
      exec "$REAL_PSQL" "$@"
    BASH
  end

  let(:evaluation_tables) do
    %w[
      evaluation_experiments
      evaluation_gold_queries
      evaluation_gold_query_sets
      evaluation_results
      evaluation_runs
      evaluation_synthetic_input_sets
      evaluation_synthetic_input_set_items
      tariff_knowledge_synthetic_atars
    ]
  end

  def create_evaluation_tables(database, value)
    psql(database, 'CREATE SCHEMA uk')

    evaluation_tables.each_with_index do |table, index|
      psql(database, <<~SQL)
        CREATE TABLE uk.#{table} (
          id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          value text NOT NULL
        );
        CREATE UNIQUE INDEX local_value_#{index} ON uk.#{table} (value);
        INSERT INTO uk.#{table} (value) VALUES ('#{value}');
      SQL
    end

    psql(database, <<~SQL)
      ALTER TABLE uk.evaluation_results
        ADD COLUMN run_id integer REFERENCES uk.evaluation_runs(id) DEFAULT 1;
      ALTER TABLE uk.evaluation_runs
        ADD COLUMN experiment_id integer REFERENCES uk.evaluation_experiments(id) DEFAULT 1;
      ALTER TABLE uk.evaluation_synthetic_input_set_items
        ADD COLUMN synthetic_atar_id integer REFERENCES uk.tariff_knowledge_synthetic_atars(id) DEFAULT 1;
    SQL
  end

  def run_replication(env_overrides = {})
    env = {
      'PATH' => "#{tempdir}/bin:#{ENV.fetch('PATH')}",
      'TMPDIR' => tempdir,
      'REAL_PSQL' => real_psql,
      'REAL_PG_RESTORE' => real_pg_restore,
      'DUMP_FIXTURE' => dump_file,
      'ENVIRONMENT' => 'development',
      'CLUSTER_NAME' => 'test-cluster',
      'SERVICES' => 'backend-web backend-worker',
      'DB_DUMP_USER' => 'dump-user',
      'DB_DUMP_PASSWORD' => 'dump-password',
      'DB_DUMP_SERVER' => 'https://dumps.example.test',
      'RESTORE_FILE' => '/tariff-merged-production.replication.dump',
      'DATABASE_URL' => target_database,
      'PGUSER' => database_user,
      'RETRY_MAX_ATTEMPTS' => '2',
      'RETRY_INITIAL_DELAY_SECONDS' => '1',
    }.merge(env_overrides)

    Open3.capture3(env, replicate_script, chdir: Rails.root.to_s)
  end

  def run_backup(source_database)
    FileUtils.mkdir_p(File.join(tempdir, 'bin'))

    write_executable('pg_dump', <<~'BASH')
      #!/usr/bin/env bash
      set -euo pipefail

      if [[ -n "${PG_DUMP_CONTAINER:-}" ]]; then
        exec docker exec --interactive --env "PGUSER=$PGUSER" "$PG_DUMP_CONTAINER" pg_dump "$@"
      fi

      exec "$REAL_PG_DUMP" "$@"
    BASH

    write_executable('aws', <<~'BASH')
      #!/usr/bin/env bash
      set -euo pipefail

      if [[ "$1 $2 $3" == "s3 cp -" ]]; then
        if [[ "$4" == *'.replication.dump.'* ]]; then
          cat > "$DUMP_FIXTURE"
        else
          cat > "$FULL_DUMP_FIXTURE"
        fi
      fi
    BASH

    env = {
      'PATH' => "#{tempdir}/bin:#{ENV.fetch('PATH')}",
      'DUMP_FIXTURE' => dump_file,
      'FULL_DUMP_FIXTURE' => full_dump_file,
      'PG_DUMP_CONTAINER' => pg_dump_container.to_s,
      'REAL_PG_DUMP' => real_pg_dump,
      'ENVIRONMENT' => 'production',
      'S3_BUCKET' => 'test-backups',
      'DATABASE_URL' => source_database,
      'PGUSER' => database_user,
    }

    Open3.capture3(env, backup_script, chdir: Rails.root.to_s)
  end

  before do
    @replicate_script = Rails.root.join('bin/db-replicate').to_s
    @backup_script = Rails.root.join('bin/backup-database').to_s
    @target_database = "replication_target_#{SecureRandom.hex(6)}"
    @tempdir = Dir.mktmpdir
    @command_log = File.join(tempdir, 'commands.log')
    @dump_file = File.join(tempdir, 'production.replication.dump')
    @full_dump_file = File.join(tempdir, 'production.sql.gz')
    @database_user = [ENV['PGUSER'], ENV['DB_USER'], ENV['USER'], 'postgres']
                       .compact
                       .uniq
                       .find do |candidate|
      _stdout, _stderr, status = Open3.capture3(
        'psql',
        '-X',
        '--username',
        candidate,
        '-d',
        'postgres',
        '-Atqc',
        'SELECT 1',
      )
      status.success?
    end
    @real_psql = ENV.fetch('PATH')
                      .split(File::PATH_SEPARATOR)
                      .map { |directory| File.join(directory, 'psql') }
                      .find { |path| File.executable?(path) }
    @real_pg_dump = ENV.fetch('PATH')
                       .split(File::PATH_SEPARATOR)
                       .map { |directory| File.join(directory, 'pg_dump') }
                       .find { |path| File.executable?(path) }
    @real_pg_restore = ENV.fetch('PATH')
                          .split(File::PATH_SEPARATOR)
                          .map { |directory| File.join(directory, 'pg_restore') }
                          .find { |path| File.executable?(path) }
    server_major = query('postgres', 'SHOW server_version_num').to_i / 10_000
    client_major = run_command(real_pg_dump, '--version')[/\d+/].to_i
    @pg_dump_container = if server_major != client_major
                           run_command(
                             'docker',
                             'ps',
                             '--filter',
                             'publish=5432',
                             '--format',
                             '{{.ID}}',
                           ).lines.first&.strip
                         end

    create_target_database
  end

  after do
    run_command('dropdb', '--username', database_user, '--if-exists', '--force', target_database)
    FileUtils.remove_entry(tempdir)
  end

  it 'restores a native archive and completes post-restore maintenance' do
    psql(target_database, 'DROP EVENT TRIGGER reassign_owned')
    build_dump
    install_replication_boundary_stubs

    _stdout, stderr, status = run_replication

    expect(status).to be_success, stderr
    expect(query(target_database, 'TABLE restore_probe')).to eq('new')
    expect(query(target_database, 'TABLE restore_probe_view')).to eq('new')
    expect(query(target_database, <<~SQL)).to eq('1')
      SELECT count(*) FROM pg_event_trigger WHERE evtname = 'reassign_owned'
    SQL
    expect(query(target_database, <<~SQL)).to eq('t')
      SELECT pg_try_advisory_lock(
        hashtextextended('trade-tariff-database-replication', 0)
      )
    SQL
  end

  it 'analyzes without rewriting tables' do
    original_filenode = query(target_database, "SELECT pg_relation_filenode('restore_probe')")
    psql(target_database, 'REFRESH MATERIALIZED VIEW restore_probe_view WITH NO DATA')

    run_command(
      'psql', '-X', '--username', database_user, '-v', 'ON_ERROR_STOP=1',
      '-d', target_database, '-f', Rails.root.join('bin/after.sql').to_s
    )

    expect(query(target_database, "SELECT pg_relation_filenode('restore_probe')")).to eq(original_filenode)
    expect(query(target_database, <<~SQL)).to eq('1')
      SELECT count(*) FROM pg_stats
      WHERE schemaname = 'public' AND tablename = 'restore_probe' AND attname = 'value'
    SQL
    expect(query(target_database, 'TABLE restore_probe_view')).to eq('old')
  end

  it 'completes post-restore maintenance when there are no materialized views' do
    psql(target_database, 'DROP MATERIALIZED VIEW restore_probe_view')
    build_dump(include_materialized_view: false)
    install_replication_boundary_stubs

    _stdout, stderr, status = run_replication

    expect(status).to be_success, stderr
    expect(query(target_database, 'TABLE restore_probe')).to eq('new')
  end

  it 'rolls back destructive statements and does not retry a deterministic SQL failure' do
    build_dump
    install_replication_boundary_stubs
    write_executable('pg_restore', <<~'BASH')
      #!/usr/bin/env bash
      set -euo pipefail
      "$REAL_PG_RESTORE" "$@"
      if [[ "$1" != '--list' ]]; then
        printf '\nSELECT 1 / 0;\n'
      fi
    BASH

    _stdout, _stderr, status = run_replication

    expect(status).not_to be_success
    expect(query(target_database, 'TABLE restore_probe')).to eq('old')
    expect(query(target_database, <<~SQL)).to eq('1')
      SELECT count(*) FROM pg_event_trigger WHERE evtname = 'reassign_owned'
    SQL
    core_restores = File.readlines(command_log).grep(/psql --single-transaction/)
    expect(core_restores.length).to eq(1)
    expect(File.readlines(command_log).grep(/aws ecs update-service .*--desired-count 1/).length).to eq(2)
  end

  it 'does not mutate services or the target when another replication holds the lock' do
    build_dump
    install_replication_boundary_stubs

    Open3.popen3(
      real_psql,
      '-X',
      '--username',
      database_user,
      '-qAt',
      target_database,
    ) do |stdin, stdout, _stderr, wait_thread|
      stdin.puts <<~SQL
        SELECT pg_try_advisory_lock(
          hashtextextended('trade-tariff-database-replication', 0)
        );
      SQL
      stdin.flush
      expect(stdout.gets&.strip).to eq('t')

      _replication_stdout, replication_stderr, status = run_replication

      expect(status).not_to be_success
      expect(replication_stderr).to include('Another database replication is already running')
      expect(File.readlines(command_log).grep(/aws ecs/)).to be_empty
      expect(query(target_database, 'TABLE restore_probe')).to eq('old')

      stdin.close
      Process.kill('TERM', wait_thread.pid) if wait_thread.alive?
    end
  end

  it 'restores a dump produced by the real backup pipeline' do
    source_database = "replication_source_#{SecureRandom.hex(6)}"
    run_command('createdb', '--username', database_user, source_database)

    begin
      psql(source_database, <<~SQL)
        CREATE TABLE restore_probe(value text);
        INSERT INTO restore_probe VALUES ('from-backup');
        CREATE MATERIALIZED VIEW restore_probe_view AS
          SELECT value FROM restore_probe;
        CREATE SCHEMA xi;
        CREATE TABLE xi.restore_probe(value text);
        INSERT INTO xi.restore_probe VALUES ('from-backup');
        CREATE FUNCTION noop_event_trigger() RETURNS event_trigger
          LANGUAGE plpgsql AS $$ BEGIN END; $$;
        CREATE EVENT TRIGGER reassign_owned
          ON ddl_command_end EXECUTE FUNCTION noop_event_trigger();
      SQL

      expect(query(source_database, 'TABLE restore_probe')).to eq('from-backup')

      _stdout, backup_stderr, backup_status = run_backup(source_database)
      expect(backup_status).to be_success, backup_stderr
      backup_sql = Zlib::GzipReader.open(full_dump_file, &:read)
      expect(backup_sql).to include('COPY public.restore_probe'), backup_stderr
      expect(backup_sql).to include("from-backup\n")

      install_replication_boundary_stubs
      _stdout, replication_stderr, replication_status = run_replication

      expect(replication_status).to be_success, replication_stderr
      expect(query(target_database, 'TABLE restore_probe')).to eq('from-backup')
      expect(query(target_database, 'TABLE xi.restore_probe')).to eq('from-backup')
      expect(query(target_database, 'TABLE restore_probe_view')).to eq('from-backup')
    ensure
      run_command('dropdb', '--username', database_user, '--if-exists', '--force', source_database)
    end
  end

  it 'preserves evaluation tables from a real backup', :aggregate_failures do
    source_database = "replication_source_#{SecureRandom.hex(6)}"
    run_command('createdb', '--username', database_user, source_database)

    begin
      create_evaluation_tables(source_database, 'production-evaluation')
      create_evaluation_tables(target_database, 'local-evaluation')

      evaluation_tables.each do |table|
        psql(target_database, <<~SQL)
          ALTER TABLE uk.#{table} ADD COLUMN local_only text DEFAULT 'newer-column';
          SELECT pg_catalog.setval('uk.#{table}_id_seq', 42);
        SQL
      end

      label_migration = '20261014090000_add_label_to_evaluation_runs.rb'
      synthetic_source_migration = '20261019130000_add_source_workbook_and_row_to_synthetic_atars.rb'
      psql(target_database, <<~SQL)
        ALTER TABLE uk.evaluation_runs ADD COLUMN label text;
        CREATE TABLE uk.schema_migrations(filename text PRIMARY KEY);
        INSERT INTO uk.schema_migrations VALUES
          ('#{label_migration}'), ('20261001000000_local_tariff.rb');
      SQL
      psql(source_database, <<~SQL)
        ALTER TABLE uk.tariff_knowledge_synthetic_atars
          ADD COLUMN source_workbook text, ADD COLUMN source_row integer;
        CREATE TABLE uk.schema_migrations(filename text PRIMARY KEY);
        INSERT INTO uk.schema_migrations VALUES
          ('#{synthetic_source_migration}'), ('20261001000000_production_tariff.rb');
        CREATE TABLE restore_probe(value text);
        INSERT INTO restore_probe VALUES ('from-backup');
        CREATE MATERIALIZED VIEW restore_probe_view AS SELECT value FROM restore_probe WITH NO DATA;
        CREATE TABLE uk.restore_probe(value text);
        INSERT INTO uk.restore_probe VALUES ('from-backup');
        CREATE SCHEMA xi;
        CREATE TABLE xi.restore_probe(value text);
        INSERT INTO xi.restore_probe VALUES ('from-backup');
        CREATE TABLE public.evaluation_runs(value text);
        INSERT INTO public.evaluation_runs VALUES ('not-excluded');
        CREATE TABLE copy_probe(value text);
        INSERT INTO copy_probe VALUES
          ('-- TRADE_TARIFF_POST_RESTORE_START'),
          ('VACUUM FULL ANALYZE;'),
          ('DROP EVENT TRIGGER reassign_owned;'),
          ('CREATE TABLE uk.evaluation_runs ('),
          ('-- Name: evaluation_runs; Type: TABLE; Schema: uk; Owner: -');
      SQL
      psql(target_database, <<~SQL)
        CREATE TABLE uk.restore_probe(value text);
        INSERT INTO uk.restore_probe VALUES ('old');
      SQL

      _stdout, backup_stderr, backup_status = run_backup(source_database)
      expect(backup_status).to be_success, backup_stderr
      backup_sql = Zlib::GzipReader.open(full_dump_file, &:read)
      expect(backup_sql).to include('DROP SCHEMA IF EXISTS uk CASCADE;')
      evaluation_tables.each do |table|
        expect(backup_sql).to include("COPY uk.#{table} ")
      end
      expect(backup_sql).to include("production-evaluation\n")
      archive_list = run_command(real_pg_restore, '--list', dump_file)
      evaluation_tables.each do |table|
        expect(archive_list).not_to include(" TABLE uk #{table} ")
        expect(archive_list).not_to include(" TABLE DATA uk #{table} ")
      end

      install_replication_boundary_stubs
      _stdout, replication_stderr, replication_status = run_replication('ENVIRONMENT' => 'staging')

      expect(replication_status).to be_success, replication_stderr
      evaluation_tables.each do |table|
        expect(query(target_database, "SELECT value, local_only FROM uk.#{table}")).to eq('local-evaluation|newer-column')
        expect(query(target_database, "INSERT INTO uk.#{table} (value) VALUES ('next-local') RETURNING id")).to eq('43')
      end
      expect(query(target_database, 'TABLE restore_probe')).to eq('from-backup')
      expect(query(target_database, 'TABLE uk.restore_probe')).to eq('from-backup')
      expect(query(target_database, 'TABLE xi.restore_probe')).to eq('from-backup')
      expect(query(target_database, 'TABLE public.evaluation_runs')).to eq('not-excluded')
      expect(query(target_database, 'SELECT value FROM copy_probe ORDER BY value'))
        .to eq(query(source_database, 'SELECT value FROM copy_probe ORDER BY value'))
      expect(query(target_database, <<~SQL)).to eq('3')
        SELECT count(*) FROM pg_constraint
        WHERE contype = 'f' AND connamespace = 'uk'::regnamespace
      SQL
      expect(query(target_database, <<~SQL)).to eq('8')
        SELECT count(*) FROM pg_indexes
        WHERE schemaname = 'uk' AND indexname LIKE 'local_value_%'
      SQL
      expect(query(target_database, 'SELECT filename FROM uk.schema_migrations ORDER BY filename').lines.map(&:strip))
        .to eq(['20261001000000_production_tariff.rb', label_migration])

      migration_directory = File.join(tempdir, 'migrations')
      FileUtils.mkdir_p(migration_directory)
      [label_migration, synthetic_source_migration].each do |migration|
        FileUtils.cp(Rails.root.join('db/migrate', migration), migration_directory)
      end
      Sequel.connect(adapter: 'postgres', database: target_database, user: database_user) do |database|
        database.run('SET search_path TO uk, public')
        expect { Sequel::Migrator.run(database, migration_directory, allow_missing_migration_files: true) }
          .not_to raise_error
        expect(database.schema(Sequel[:uk][:tariff_knowledge_synthetic_atars]).map(&:first))
          .to include(:source_workbook, :source_row)
      end
    ensure
      run_command('dropdb', '--username', database_user, '--if-exists', '--force', source_database)
    end
  end

  it 'rejects an archive containing excluded tables' do
    psql(target_database, <<~SQL)
      CREATE SCHEMA uk;
      CREATE TABLE uk.evaluation_runs(value text);
      INSERT INTO uk.evaluation_runs VALUES ('local-evaluation');
    SQL
    run_command(real_pg_dump, '--format=custom', '--username', database_user, '--file', dump_file, target_database)
    install_replication_boundary_stubs

    _stdout, stderr, status = run_replication

    expect(status).not_to be_success
    expect(stderr).to include('Replication archive contains excluded table uk.evaluation_runs')
    expect(query(target_database, 'TABLE uk.evaluation_runs')).to eq('local-evaluation')
    expect(query(target_database, 'TABLE restore_probe')).to eq('old')
  end

  it 'rolls back when the dump stream fails' do
    build_dump
    install_replication_boundary_stubs
    write_executable('pg_restore', <<~'BASH')
      #!/usr/bin/env bash
      set -euo pipefail
      "$REAL_PG_RESTORE" "$@"
