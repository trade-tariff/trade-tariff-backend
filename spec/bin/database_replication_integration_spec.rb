# frozen_string_literal: true

require 'open3'
require 'securerandom'
require 'tmpdir'
require 'zlib'

# These examples run the real bin/backup-database and bin/db-replicate against disposable
# PostgreSQL databases, with real pg_dump, pg_restore and psql. Only aws and curl are stubbed.
# pg_dump --filter needs a client of version 17 or newer, so the examples skip when none is installed.
RSpec.describe 'database replication with PostgreSQL' do
  attr_reader :backup_script,
              :client_bin,
              :command_log,
              :database_user,
              :replicate_script,
              :s3_dir,
              :target_database,
              :tempdir

  def evaluation_only_migration = '20261014090000_add_label_to_evaluation_runs.rb'

  def shared_evaluation_migration = '20260803000001_create_evaluation_experiments.rb'

  def production_only_evaluation_migration = '20261019130000_add_source_workbook_and_row_to_synthetic_atars.rb'

  def evaluation_tables
    %w[
      evaluation_experiments
      evaluation_gold_queries
      evaluation_gold_query_sets
      evaluation_results
      evaluation_runs
      evaluation_synthetic_input_set_items
      evaluation_synthetic_input_sets
      tariff_knowledge_synthetic_atars
    ]
  end

  def run_command(*command, stdin_data: '')
    stdout, stderr, status = Open3.capture3(*command, stdin_data:)
    raise "#{command.join(' ')} failed:\n#{stdout}\n#{stderr}" unless status.success?

    stdout
  end

  def psql(database, sql)
    run_command('psql', '-X', '--username', database_user, '-v', 'ON_ERROR_STOP=1', '-q', database, '-c', sql)
  end

  def query(database, sql)
    run_command('psql', '-X', '--username', database_user, '-Atq', database, '-c', sql).strip
  end

  def write_executable(name, contents)
    path = File.join(tempdir, 'bin', name)
    File.write(path, contents)
    File.chmod(0o755, path)
  end

  def postgres_client_bin(minimum_major:)
    directories = ENV.fetch('PATH').split(File::PATH_SEPARATOR) +
      %w[
        /opt/homebrew/opt/postgresql@18/bin
        /opt/homebrew/opt/postgresql@17/bin
        /usr/lib/postgresql/18/bin
        /usr/lib/postgresql/17/bin
      ]

    directories.find do |directory|
      tools = %w[pg_dump pg_restore psql].map { |tool| File.join(directory, tool) }
      next false unless tools.all? { |path| File.executable?(path) }

      version, = Open3.capture2e(tools.first, '--version')
      version[/\d+/].to_i >= minimum_major
    end
  end

  # The schema both production and staging share: one tariff table, a materialized view over it,
  # the migration history table, and the eight evaluation-related tables with their real foreign keys.
  def create_tariff_schema(database)
    psql(database, <<~SQL)
      CREATE SCHEMA uk;
      CREATE TABLE uk.goods_nomenclatures(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code text);
      CREATE MATERIALIZED VIEW uk.goods_nomenclature_codes AS SELECT code FROM uk.goods_nomenclatures;
      CREATE TABLE uk.schema_migrations(filename text NOT NULL);
      CREATE TABLE uk.tariff_knowledge_synthetic_atars(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label text);
      CREATE TABLE uk.evaluation_synthetic_input_sets(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text);
      CREATE TABLE uk.evaluation_synthetic_input_set_items(
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        set_id integer REFERENCES uk.evaluation_synthetic_input_sets(id) ON DELETE CASCADE,
        synthetic_atar_id integer REFERENCES uk.tariff_knowledge_synthetic_atars(id) ON DELETE RESTRICT
      );
      CREATE TABLE uk.evaluation_gold_query_sets(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text);
      CREATE TABLE uk.evaluation_gold_queries(
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        set_id integer REFERENCES uk.evaluation_gold_query_sets(id) ON DELETE CASCADE
      );
      CREATE TABLE uk.evaluation_experiments(
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name text,
        gold_query_set_id integer REFERENCES uk.evaluation_gold_query_sets(id) ON DELETE RESTRICT,
        synthetic_input_set_id integer REFERENCES uk.evaluation_synthetic_input_sets(id) ON DELETE RESTRICT
      );
      CREATE TABLE uk.evaluation_runs(
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        label text,
        experiment_id integer REFERENCES uk.evaluation_experiments(id) ON DELETE RESTRICT
      );
      CREATE TABLE uk.evaluation_results(
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        run_id integer REFERENCES uk.evaluation_runs(id) ON DELETE CASCADE
      );
      CREATE FUNCTION public.noop_event_trigger() RETURNS event_trigger
        LANGUAGE plpgsql AS $$ BEGIN END; $$;
      CREATE EVENT TRIGGER reassign_owned
        ON ddl_command_end EXECUTE FUNCTION public.noop_event_trigger();
    SQL
  end

  def seed_evaluation_data(database, prefix:, runs:)
    psql(database, <<~SQL)
      INSERT INTO uk.tariff_knowledge_synthetic_atars(label) VALUES ('#{prefix}-atar');
      INSERT INTO uk.evaluation_synthetic_input_sets(name) VALUES ('#{prefix}-set');
      INSERT INTO uk.evaluation_synthetic_input_set_items(set_id, synthetic_atar_id) VALUES (1, 1);
      INSERT INTO uk.evaluation_gold_query_sets(name) VALUES ('#{prefix}-gold-set');
      INSERT INTO uk.evaluation_gold_queries(set_id) VALUES (1);
      INSERT INTO uk.evaluation_experiments(name, synthetic_input_set_id) VALUES ('#{prefix}-experiment', 1);
      INSERT INTO uk.evaluation_runs(label, experiment_id)
        SELECT '#{prefix}-run-' || n, 1 FROM generate_series(1, #{runs}) AS n;
      INSERT INTO uk.evaluation_results(run_id) VALUES (1);
    SQL
  end

  def create_production_database
    database = "replication_source_#{SecureRandom.hex(6)}"
    run_command('createdb', '--username', database_user, database)
    create_tariff_schema(database)
    psql(database, <<~SQL)
      INSERT INTO uk.goods_nomenclatures(code) VALUES ('0101-production');
      INSERT INTO uk.schema_migrations VALUES
        ('20200101000000_create_goods.rb'),
        ('#{shared_evaluation_migration}'),
        ('#{production_only_evaluation_migration}');
    SQL
    seed_evaluation_data(database, prefix: 'production', runs: 3)
    database
  end

  def create_target_database
    run_command('createdb', '--username', database_user, target_database)
    create_tariff_schema(target_database)
    psql(target_database, <<~SQL)
      INSERT INTO uk.goods_nomenclatures(code) VALUES ('0101-staging');
      REFRESH MATERIALIZED VIEW uk.goods_nomenclature_codes;
      INSERT INTO uk.schema_migrations VALUES
        ('20200101000001_local_only.rb'),
        ('#{shared_evaluation_migration}'),
        ('#{evaluation_only_migration}');
      ALTER TABLE uk.evaluation_runs ADD COLUMN newer_local_column text;
    SQL
    seed_evaluation_data(target_database, prefix: 'staging', runs: 1)
    psql(target_database, "UPDATE uk.evaluation_runs SET newer_local_column = 'kept'")
  end

  def evaluation_snapshot(database)
    evaluation_tables.index_with do |table|
      query(database, "SELECT coalesce(md5(string_agg(t::text, '|' ORDER BY t.id)), 'empty') FROM uk.#{table} t")
    end
  end

  def migrations(database)
    query(database, 'SELECT filename FROM uk.schema_migrations ORDER BY filename').lines.map(&:strip)
  end

  def install_replication_boundary_stubs
    FileUtils.mkdir_p(File.join(tempdir, 'bin'))
    FileUtils.mkdir_p(s3_dir)
    FileUtils.touch(command_log)

    write_executable('aws', <<~'BASH')
      #!/usr/bin/env bash
      set -euo pipefail
      echo "aws $*" >> "$TMPDIR/commands.log"

      key_of() { echo "${1#s3://*/}"; }

      case "$1 $2" in
        "ecs describe-services")
          echo 1
          ;;
        "s3 cp")
          destination="$S3_DIR/$(key_of "$4")"
          mkdir -p "$(dirname "$destination")"

          if [[ "$3" == "-" ]]; then
            cat > "$destination"
          else
            cp "$S3_DIR/$(key_of "$3")" "$destination"
          fi
          ;;
        "s3 rm")
          rm -f "$S3_DIR/$(key_of "$3")"
          ;;
      esac
    BASH

    write_executable('curl', <<~'BASH')
      #!/usr/bin/env bash
      set -euo pipefail
      echo "curl $*" >> "$TMPDIR/commands.log"

      while [[ $# -gt 0 ]]; do
        if [[ "$1" == "--output" ]]; then
          cp "$DUMP_FIXTURE" "$2"
          exit 0
        fi
        shift
      done

      exit 1
    BASH

    write_executable('psql', <<~'BASH')
      #!/usr/bin/env bash
      set -euo pipefail
      echo "psql $*" >> "$TMPDIR/commands.log"
      exec "$REAL_PSQL" "$@"
    BASH
  end

  def script_env(extra = {})
    {
      'PATH' => "#{tempdir}/bin:#{client_bin}:#{ENV.fetch('PATH')}",
      'TMPDIR' => tempdir,
      'S3_DIR' => s3_dir,
      'REAL_PSQL' => File.join(client_bin, 'psql'),
      'REAL_PG_RESTORE' => File.join(client_bin, 'pg_restore'),
      'PGUSER' => database_user,
    }.merge(extra)
  end

  def run_replication(restore_file: '/tariff-merged-production.replication.dump', archive: replication_archive_path)
    env = script_env(
      'DUMP_FIXTURE' => archive,
      'ENVIRONMENT' => 'development',
      'CLUSTER_NAME' => 'test-cluster',
      'SERVICES' => 'backend-web backend-worker',
      'DB_DUMP_USER' => 'dump-user',
      'DB_DUMP_PASSWORD' => 'dump-password',
      'DB_DUMP_SERVER' => 'https://dumps.example.test',
      'RESTORE_FILE' => restore_file,
      'DATABASE_URL' => target_database,
      'RETRY_MAX_ATTEMPTS' => '2',
      'RETRY_INITIAL_DELAY_SECONDS' => '1',
    )

    Open3.capture3(env, replicate_script, chdir: Rails.root.to_s)
  end

  def run_backup(source_database)
    env = script_env(
      'ENVIRONMENT' => 'production',
      'S3_BUCKET' => 'test-backups',
      'DATABASE_URL' => source_database,
    )

    Open3.capture3(env, backup_script, chdir: Rails.root.to_s)
  end

  def replication_archive_path
    File.join(s3_dir, 'tariff-merged-production.replication.dump')
  end

  def full_backup_path
    File.join(s3_dir, 'tariff-merged-production.sql.gz')
  end

  def publish_replication_archive_from(source_database)
    _stdout, stderr, status = run_backup(source_database)
    raise "backup failed:\n#{stderr}" unless status.success?
  end

  before do
    @replicate_script = Rails.root.join('bin/db-replicate').to_s
    @backup_script = Rails.root.join('bin/backup-database').to_s
    @target_database = "replication_target_#{SecureRandom.hex(6)}"
    @tempdir = Dir.mktmpdir
    @s3_dir = File.join(tempdir, 's3')
    @command_log = File.join(tempdir, 'commands.log')
    @database_user = [ENV['PGUSER'], ENV['DB_USER'], ENV['USER'], 'postgres']
                       .compact
                       .uniq
                       .find do |candidate|
      _stdout, _stderr, status = Open3.capture3(
        'psql',
        '-X',
        '--username',
        candidate,
        '-d',
        'postgres',
        '-Atqc',
        'SELECT 1',
      )
      status.success?
    end

    server_major = query('postgres', 'SHOW server_version_num').to_i / 10_000
    @client_bin = postgres_client_bin(minimum_major: [17, server_major].max)
    skip 'needs PostgreSQL client tools of version 17 or newer (pg_dump --filter)' unless client_bin

    install_replication_boundary_stubs
    create_target_database
  end

  after do
    run_command('dropdb', '--username', database_user, '--if-exists', '--force', target_database) if database_user
    FileUtils.remove_entry(tempdir) if tempdir
  end

  describe 'bin/backup-database' do
    let(:source_database) { create_production_database }

    after do
      run_command('dropdb', '--username', database_user, '--if-exists', '--force', source_database)
    end

    it 'keeps the recovery backup complete, evaluation tables included' do
      publish_replication_archive_from(source_database)

      full_backup = Zlib::GzipReader.open(full_backup_path, &:read)

      expect(full_backup).to include('COPY uk.evaluation_runs')
      expect(full_backup).to include('production-run-3')
      expect(full_backup).to include('COPY uk.tariff_knowledge_synthetic_atars')
    end

    it 'publishes a separate replication archive without the evaluation tables or their dependent objects' do
      publish_replication_archive_from(source_database)

      listing = run_command(File.join(client_bin, 'pg_restore'), '--list', replication_archive_path)

      expect(listing).to include('TABLE DATA uk goods_nomenclatures')
      expect(listing).not_to include('evaluation_')
      expect(listing).not_to include('tariff_knowledge_synthetic_atars')
    end

    it 'publishes the replication archive under the latest key and the dated archive key' do
      publish_replication_archive_from(source_database)

      dated_archives = Dir.glob(File.join(s3_dir, '*/*/*/tariff-merged-production.replication.dump'))

      expect(File).to exist(replication_archive_path)
      expect(dated_archives.length).to eq(1)
    end

    it 'leaves the previous replication archive in place, and still publishes the recovery backup, when its dump fails' do
      FileUtils.mkdir_p(s3_dir)
      File.write(replication_archive_path, 'previous archive')
      write_executable('pg_dump', <<~'BASH')
        #!/usr/bin/env bash
        for argument in "$@"; do
          if [[ "$argument" == --format=custom ]]; then
            printf 'partial archive'
            exit 42
          fi
        done

        exec "$REAL_PG_DUMP" "$@"
      BASH

      env = script_env(
        'REAL_PG_DUMP' => File.join(client_bin, 'pg_dump'),
        'ENVIRONMENT' => 'production',
        'S3_BUCKET' => 'test-backups',
        'DATABASE_URL' => source_database,
      )
      _stdout, _stderr, status = Open3.capture3(env, backup_script, chdir: Rails.root.to_s)

      expect(status.exitstatus).to eq(4)
      expect(File.read(replication_archive_path)).to eq('previous archive')
      expect(File).to exist(full_backup_path)
    end
  end

  describe 'bin/db-replicate' do
    let(:source_database) { create_production_database }

    before do
      publish_replication_archive_from(source_database)
    end

    after do
      run_command('dropdb', '--username', database_user, '--if-exists', '--force', source_database) if client_bin
    end

    it 'replaces tariff data from production and leaves all eight evaluation tables exactly as they were' do
      evaluation_before = evaluation_snapshot(target_database)

      _stdout, stderr, status = run_replication

      expect(status).to be_success, stderr
      expect(query(target_database, 'TABLE uk.goods_nomenclatures')).to eq('1|0101-production')
      expect(evaluation_snapshot(target_database)).to eq(evaluation_before)
    end

    it 'keeps newer local columns and sequence state on the evaluation tables' do
      _stdout, stderr, status = run_replication

      expect(status).to be_success, stderr
      expect(query(target_database, 'SELECT newer_local_column FROM uk.evaluation_runs')).to eq('kept')
      expect(query(target_database, 'SELECT last_value FROM uk.evaluation_runs_id_seq')).to eq('1')
      expect(query(target_database, "INSERT INTO uk.evaluation_runs(label) VALUES ('next') RETURNING id")).to start_with('2')
    end

    it 'keeps the schemas, so replacing production tables cannot cascade into the retained ones' do
      _stdout, stderr, status = run_replication

      expect(status).to be_success, stderr
      expect(query(target_database, "SELECT count(*) FROM pg_namespace WHERE nspname = 'uk'")).to eq('1')
      expect(query(target_database, 'SELECT count(*) FROM uk.evaluation_experiments')).to eq('1')
    end

    it 'keeps the local applied state of evaluation migrations and restores the rest of the history from production' do
      _stdout, stderr, status = run_replication

      expect(status).to be_success, stderr
      expect(migrations(target_database)).to eq(
        [
          '20200101000000_create_goods.rb',
          shared_evaluation_migration,
          evaluation_only_migration,
        ].sort,
      )
    end

    it 'leaves a production-only evaluation migration unapplied, because the retained tables do not have its change' do
      _stdout, stderr, status = run_replication

      expect(status).to be_success, stderr
      expect(migrations(target_database)).not_to include(production_only_evaluation_migration)
    end

    it 'refreshes materialized views in post-restore maintenance instead of restoring their data' do
      _stdout, stderr, status = run_replication

      expect(status).to be_success, stderr
      expect(query(target_database, 'TABLE uk.goods_nomenclature_codes')).to eq('0101-production')
    end

    it 'releases the replication lock when it finishes' do
      _stdout, stderr, status = run_replication

      expect(status).to be_success, stderr
      expect(query(target_database, <<~SQL)).to eq('t')
        SELECT pg_try_advisory_lock(hashtextextended('trade-tariff-database-replication', 0))
      SQL
    end

    it 'refuses the full recovery backup before touching services or the database' do
      full_backup = File.join(s3_dir, 'tariff-merged-production.sql.gz')
      evaluation_before = evaluation_snapshot(target_database)

      _stdout, stderr, status = run_replication(restore_file: '/tariff-merged-production.sql.gz', archive: full_backup)

      expect(status).not_to be_success
      expect(stderr).to include('replication archive')
      expect(File.readlines(command_log).grep(/aws ecs|curl/)).to be_empty
      expect(query(target_database, 'TABLE uk.goods_nomenclatures')).to eq('1|0101-staging')
      expect(evaluation_snapshot(target_database)).to eq(evaluation_before)
    end

    it 'rejects an archive that contains an evaluation table, and leaves the database and services as they were' do
      unfiltered = File.join(tempdir, 'unfiltered.replication.dump')
      run_command(File.join(client_bin, 'pg_dump'), '--format=custom', '--no-acl', '--no-owner', '--username', database_user, '--file', unfiltered, source_database)
      evaluation_before = evaluation_snapshot(target_database)

      _stdout, stderr, status = run_replication(archive: unfiltered)

      expect(status).not_to be_success
      expect(stderr).to include('uk.evaluation_')
      expect(query(target_database, 'TABLE uk.goods_nomenclatures')).to eq('1|0101-staging')
      expect(evaluation_snapshot(target_database)).to eq(evaluation_before)
      expect(File.readlines(command_log).grep(/aws ecs update-service .*--desired-count 1/).length).to eq(2)
    end

    it 'rejects a file that is not an archive' do
      not_an_archive = File.join(tempdir, 'not-an-archive.replication.dump')
      File.write(not_an_archive, 'SELECT 1;')

      _stdout, stderr, status = run_replication(archive: not_an_archive)

      expect(status).not_to be_success
      expect(stderr).to include('not a valid replication archive')
      expect(query(target_database, 'TABLE uk.goods_nomenclatures')).to eq('1|0101-staging')
    end

    it 'rolls everything back, and does not retry, when a restore statement fails' do
      psql(target_database, 'CREATE VIEW uk.local_dependent_view AS SELECT code FROM uk.goods_nomenclatures')
      evaluation_before = evaluation_snapshot(target_database)

      _stdout, _stderr, status = run_replication

      expect(status).not_to be_success
      expect(query(target_database, 'TABLE uk.goods_nomenclatures')).to eq('1|0101-staging')
      expect(migrations(target_database)).to include('20200101000001_local_only.rb')
      expect(evaluation_snapshot(target_database)).to eq(evaluation_before)
      expect(File.readlines(command_log).grep(/psql .*ON_ERROR_STOP=1/).length).to eq(1)
      expect(File.readlines(command_log).grep(/aws ecs update-service .*--desired-count 1/).length).to eq(2)
    end

    it 'rolls everything back when the archive producer fails part-way through' do
      write_executable('pg_restore', <<~'BASH')
        #!/usr/bin/env bash
        for argument in "$@"; do
          if [[ "$argument" == --file=- ]]; then
            "$REAL_PG_RESTORE" "$@" | head -n 80
            exit 1
          fi
        done

        exec "$REAL_PG_RESTORE" "$@"
      BASH
      evaluation_before = evaluation_snapshot(target_database)

      _stdout, _stderr, status = run_replication

      expect(status).not_to be_success
      expect(query(target_database, 'TABLE uk.goods_nomenclatures')).to eq('1|0101-staging')
      expect(migrations(target_database)).to include('20200101000001_local_only.rb')
      expect(evaluation_snapshot(target_database)).to eq(evaluation_before)
    end

    it 'does not mutate services or the target when another replication holds the lock' do
      Open3.popen3(
        File.join(client_bin, 'psql'),
        '-X',
        '--username',
        database_user,
        '-qAt',
        target_database,
      ) do |stdin, stdout, _stderr, wait_thread|
        stdin.puts <<~SQL
          SELECT pg_try_advisory_lock(
            hashtextextended('trade-tariff-database-replication', 0)
          );
        SQL
        stdin.flush
        expect(stdout.gets&.strip).to eq('t')

        _replication_stdout, replication_stderr, status = run_replication

        expect(status).not_to be_success
        expect(replication_stderr).to include('Another database replication is already running')
        expect(File.readlines(command_log).grep(/aws ecs/)).to be_empty
        expect(query(target_database, 'TABLE uk.goods_nomenclatures')).to eq('1|0101-staging')

        stdin.close
        Process.kill('TERM', wait_thread.pid) if wait_thread.alive?
      end
    end
  end

  it 'analyzes without rewriting tables' do
    original_filenode = query(target_database, "SELECT pg_relation_filenode('uk.goods_nomenclatures')")
    psql(target_database, 'REFRESH MATERIALIZED VIEW uk.goods_nomenclature_codes WITH NO DATA')

    run_command(
      File.join(client_bin, 'psql'), '-X', '--username', database_user, '-v', 'ON_ERROR_STOP=1',
      '-d', target_database, '-f', Rails.root.join('bin/after.sql').to_s
    )

    expect(query(target_database, "SELECT pg_relation_filenode('uk.goods_nomenclatures')")).to eq(original_filenode)
    expect(query(target_database, <<~SQL)).to eq('1')
      SELECT count(*) FROM pg_stats
      WHERE schemaname = 'uk' AND tablename = 'goods_nomenclatures' AND attname = 'code'
    SQL
    expect(query(target_database, 'TABLE uk.goods_nomenclature_codes')).to eq('0101-staging')
  end

  it 'does not replace the latest backup when pg_dump fails' do
    write_executable('pg_dump', <<~'BASH')
      #!/usr/bin/env bash
      printf '%s\n' '-- incomplete dump'
      exit 42
    BASH

    write_executable('gzip', <<~'BASH')
      #!/usr/bin/env bash
      exec cat
    BASH

    env = script_env('ENVIRONMENT' => 'production', 'S3_BUCKET' => 'test-backups', 'DATABASE_URL' => target_database)

    _stdout, _stderr, status = Open3.capture3(env, backup_script, chdir: Rails.root.to_s)
    promotions = File.readlines(command_log, chomp: true).grep(%r{aws s3 cp s3://})

    expect(status.exitstatus).to eq(2)
    expect(promotions).to be_empty
    expect(File).not_to exist(full_backup_path)
    expect(File).not_to exist(replication_archive_path)
  end
end
